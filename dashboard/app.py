# ================================================================
# PROJECT PATHS
# ================================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

DATA_PATH = PROJECT_ROOT / "data" / "sessions.json"

AUDIT_DIR = PROJECT_ROOT / "audit"
DASHBOARD_AUDIT_PATH = AUDIT_DIR / "dashboard_run.jsonl"

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


from src.recovery_agent import process_sessions
from src.revenue_simulator import (
    simulate_results,
    summarize_revenue,
)


