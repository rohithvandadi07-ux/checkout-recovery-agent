# ================================================================
# RECOVERY PERFORMANCE
# ================================================================

st.subheader(
    "Recovery Performance by Cause"
)

recovery_df = df[
    df["eligible"] == True
].copy()


if not recovery_df.empty:

    recovery_by_cause = (
        recovery_df
        .groupby("cause")
        .agg(
            eligible_sessions=(
                "session_id",
                "count",
            ),
            recovered_sessions=(
                "recovered",
                "sum",
            ),
            eligible_value=(
                "cart_value",
                "sum",
            ),
            recovered_revenue=(
                "recovered_revenue",
                "sum",
            ),
        )
        .sort_index()
    )

    recovery_by_cause[
        "recovery_rate"
    ] = (
        recovery_by_cause[
            "recovered_sessions"
        ]
        / recovery_by_cause[
            "eligible_sessions"
        ]
    )

    recovery_by_cause[
        "revenue_recovery_rate"
    ] = (
        recovery_by_cause[
            "recovered_revenue"
        ]
        / recovery_by_cause[
            "eligible_value"
        ]
    )

    display_df = recovery_by_cause.copy()

    display_df[
        "recovery_rate"
    ] *= 100

    display_df[
        "revenue_recovery_rate"
    ] *= 100

    st.dataframe(
        display_df.style.format(
            {
                "eligible_sessions": "{:,}",
                "recovered_sessions": "{:,}",
                "eligible_value": "₹{:,.2f}",
                "recovered_revenue": "₹{:,.2f}",
                "recovery_rate": "{:.2f}%",
                "revenue_recovery_rate": "{:.2f}%",
            }
        ),
        use_container_width=True,
    )

